#include "math_2.h"
#include <cmath>


double MyMath::add(double value1, double value2)
{
	return value1 + value2;
}

double MyMath::sub(double value1, double value2)
{
	return value1 - value2;
}

double MyMath::mult(double value1, double value2)
{
	return value1 * value2;
}

double MyMath::div(double value1, double value2)
{
	return value1 / value2;
}

double MyMath::pow2(double value1, double value2)
{
	return pow(value1, value2);
}
